  <h2>Reports and analytics <a class="anchor" href="#reports">#</a></h2>

  <h3>A campaign’s report</h3>
  <p><b>Campaigns → Reports</b> lists every campaign that was sent, with <b>Sent</b>, <b>Skipped</b>, <b>Failed</b>, open rate, click rate and date. Open one to see four cards:</p>
  <div class="table-wrap"><table>
    <thead><tr><th>Card</th><th>Meaning</th></tr></thead>
    <tbody>
      <tr><td><b>Delivered</b></td><td>Messages handed to the email or SMS service successfully.</td></tr>
      <tr><td><b>Skipped</b></td><td>People with no email address (or phone number for SMS), so nothing could be sent. Unsubscribed people are not counted: they are simply not sent to.</td></tr>
      <tr><td><b>Failed</b></td><td>The service refused the message. The reason is shown.</td></tr>
      <tr><td><b>Logged only</b></td><td>The service in use is <i>Log only</i>: written to a log, nothing delivered.</td></tr>
    </tbody>
  </table></div>
  <p>Email campaigns also show open and click rates, a chart over time and the most clicked links. The <b>Delivery Reports</b> table lists every person with their status and the reason, and can be filtered by <i>Delivered, Skipped, Failed, Logged only, Queued</i> or searched by name, email or phone. <b>Export recipients (CSV)</b> downloads the list.</p>
  <div class="note"><b>A sent campaign is a snapshot.</b> Its page shows how many people the audience had <i>when it was sent</i>. People you add later are not part of it.</div>

  <h3>Message logs</h3>
  <p><b>Analytics → Message logs</b> lists every email and text that was sent or tried: campaigns, automations, form replies, test messages and staff notifications. Filter by channel, source, service, status and date. Click a row to see the full message and, for a failure, what to do about it. It is refreshed automatically while anything is still queued.</p>

  <h3>Analytics</h3>
  <p>Seven reports, each over 7, 14, 30, 60 or 90 days:</p>
  <ul>
    <li><b>Overview</b>: headline numbers compared with the previous period.</li>
    <li><b>Email</b> and <b>SMS</b>: volumes, opens and clicks, per-campaign tables, top links.</li>
    <li><b>Delivery &amp; errors</b>: failures and skips by reason and service, and the latest failures.</li>
    <li><b>People</b>: growth, where people come from, subscriptions, engagement.</li>
    <li><b>Forms &amp; pages</b>: views, submissions and conversion.</li>
  </ul>
  <p><b>Automation History</b> shows people currently moving through workflows and a step-by-step log of what each workflow did.</p>
